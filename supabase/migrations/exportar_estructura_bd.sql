-- Backup de la ESTRUCTURA de la base (módulo Backup, solo admin) — 2026-10-17
--
-- backup.html descargaba solo los DATOS (Excel). Esta migración agrega la
-- exportación de la estructura como script .sql:
--
--   public._estructura_bd_ddl()      Arma el script leyendo el catálogo de Postgres.
--                                    Sin permisos para anon/authenticated (solo se llama
--                                    desde el wrapper).
--   public.exportar_estructura_bd()  Wrapper que el panel invoca por RPC. Verifica que
--                                    quien llama sea un usuario ACTIVO con rol 'admin';
--                                    si no, lanza 42501.
--
-- Contenido del script (esquemas public y, para políticas y buckets, storage):
--   secuencias, tablas (columnas, identity, defaults), funciones y procedimientos,
--   constraints (PK, UNIQUE, CHECK, FK), índices, triggers, RLS + políticas,
--   comentarios, GRANTs de tablas y funciones (anon/authenticated/service_role),
--   publicación realtime, buckets de Storage y tareas pg_cron.
-- NO incluye: datos, usuarios de Auth, archivos de Storage, secretos de las Edge
-- Functions, configuración de Auth ni GRANTs por columna.
--
-- Los scripts salen en orden de restauración (pg_dump): tablas → funciones →
-- constraints → índices → triggers → RLS → políticas → grants.
--
-- Ejecutado en producción el 2026-10-17. Idempotente (CREATE OR REPLACE).

CREATE OR REPLACE FUNCTION public._estructura_bd_ddl()
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $fn$
DECLARE
  v text;
  s text;
BEGIN
  v := E'-- ============================================================\n'
    || E'-- ESTRUCTURA DE LA BASE DE DATOS (solo esquema, SIN datos)\n'
    || E'-- Generada: ' || to_char(now() AT TIME ZONE 'America/Bogota', 'YYYY-MM-DD HH24:MI') || E' (hora Colombia)\n'
    || E'-- Origen: módulo Backup del panel (exportar_estructura_bd)\n'
    || E'--\n'
    || E'-- NO incluye: datos (usar el backup en Excel), usuarios de Auth, archivos de\n'
    || E'-- Storage, secretos de las Edge Functions ni la configuración de Auth.\n'
    || E'-- El código de las Edge Functions está en supabase/functions/ del repositorio.\n'
    || E'-- ============================================================\n\n'
    || E'SET check_function_bodies = false;\n'
    || E'SET client_min_messages = warning;\n';

  -- ── Extensiones (referencia) ──
  SELECT string_agg(format('-- %s %s (esquema %s)', e.extname, e.extversion, n.nspname), E'\n' ORDER BY e.extname)
    INTO s
    FROM pg_catalog.pg_extension e
    JOIN pg_catalog.pg_namespace n ON n.oid = e.extnamespace
   WHERE e.extname <> 'plpgsql';
  v := v || E'\n-- ── 1. Extensiones instaladas (referencia; se habilitan en Database → Extensions) ──\n'
         || coalesce(s, '-- (ninguna)') || E'\n';

  -- ── Secuencias sueltas (las de columnas identity las crea la propia columna) ──
  SELECT string_agg(
           format('CREATE SEQUENCE %I.%I AS %s START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s%s;',
                  'public', c.relname, pg_catalog.format_type(q.seqtypid, NULL),
                  q.seqstart, q.seqincrement, q.seqmin, q.seqmax, q.seqcache,
                  CASE WHEN q.seqcycle THEN ' CYCLE' ELSE '' END),
           E'\n' ORDER BY c.relname)
    INTO s
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_sequence q ON q.seqrelid = c.oid
   WHERE c.relnamespace = 'public'::regnamespace
     AND c.relkind = 'S'
     AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend d
                      WHERE d.classid = 'pg_catalog.pg_class'::regclass AND d.objid = c.oid AND d.deptype = 'i')
     AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                      WHERE e.classid = 'pg_catalog.pg_class'::regclass AND e.objid = c.oid AND e.deptype = 'e');
  v := v || E'\n-- ── 2. Secuencias ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  -- ── Tablas ──
  SELECT string_agg(
           format(E'CREATE TABLE %I.%I (\n%s\n);', 'public', t.relname,
             (SELECT string_agg(
                       format('  %I %s%s%s',
                              a.attname,
                              pg_catalog.format_type(a.atttypid, a.atttypmod),
                              CASE
                                WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                                WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                                WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid)
                                ELSE ''
                              END,
                              CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
                       E',\n' ORDER BY a.attnum)
                FROM pg_catalog.pg_attribute a
                LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
               WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped)),
           E'\n\n' ORDER BY t.relname)
    INTO s
    FROM pg_catalog.pg_class t
   WHERE t.relnamespace = 'public'::regnamespace
     AND t.relkind = 'r'
     AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                      WHERE e.classid = 'pg_catalog.pg_class'::regclass AND e.objid = t.oid AND e.deptype = 'e');
  v := v || E'\n-- ── 3. Tablas ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  -- Secuencias "serial" (dueñas de una columna)
  SELECT string_agg(
           format('ALTER SEQUENCE %I.%I OWNED BY %I.%I.%I;', 'public', sc.relname, 'public', tc.relname, a.attname),
           E'\n' ORDER BY sc.relname)
    INTO s
    FROM pg_catalog.pg_depend d
    JOIN pg_catalog.pg_class sc ON sc.oid = d.objid
    JOIN pg_catalog.pg_class tc ON tc.oid = d.refobjid
    JOIN pg_catalog.pg_attribute a ON a.attrelid = tc.oid AND a.attnum = d.refobjsubid
   WHERE d.classid = 'pg_catalog.pg_class'::regclass
     AND d.refclassid = 'pg_catalog.pg_class'::regclass
     AND d.deptype = 'a'
     AND sc.relkind = 'S'
     AND sc.relnamespace = 'public'::regnamespace
     AND tc.relnamespace = 'public'::regnamespace;
  IF s IS NOT NULL THEN
    v := v || E'\n-- Secuencias propiedad de una columna\n' || s || E'\n';
  END IF;

  -- ── Funciones y procedimientos ──
  SELECT string_agg(
           pg_catalog.rtrim(pg_catalog.pg_get_functiondef(p.oid), E'\n') || E';\n',
           E'\n' ORDER BY p.proname, p.oid)
    INTO s
    FROM pg_catalog.pg_proc p
   WHERE p.pronamespace = 'public'::regnamespace
     AND p.prokind IN ('f', 'p')
     AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                      WHERE e.classid = 'pg_catalog.pg_proc'::regclass AND e.objid = p.oid AND e.deptype = 'e');
  v := v || E'\n-- ── 4. Funciones y procedimientos ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  -- ── Constraints (PK, UNIQUE, EXCLUDE, CHECK y al final las FK) ──
  SELECT string_agg(
           format('ALTER TABLE ONLY %I.%I ADD CONSTRAINT %I %s;',
                  'public', c.relname, k.conname, pg_catalog.pg_get_constraintdef(k.oid)),
           E'\n' ORDER BY CASE k.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'x' THEN 3 WHEN 'c' THEN 4 ELSE 5 END,
                          c.relname, k.conname)
    INTO s
    FROM pg_catalog.pg_constraint k
    JOIN pg_catalog.pg_class c ON c.oid = k.conrelid
   WHERE c.relnamespace = 'public'::regnamespace
     AND c.relkind = 'r'
     AND k.contype IN ('p', 'u', 'x', 'c', 'f')
     AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                      WHERE e.classid = 'pg_catalog.pg_class'::regclass AND e.objid = c.oid AND e.deptype = 'e');
  v := v || E'\n-- ── 5. Constraints (PK, UNIQUE, CHECK, FK) ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  -- ── Índices (los que respaldan una PK/UNIQUE ya salen en constraints) ──
  SELECT string_agg(pg_catalog.pg_get_indexdef(i.indexrelid) || ';', E'\n' ORDER BY c.relname, ic.relname)
    INTO s
    FROM pg_catalog.pg_index i
    JOIN pg_catalog.pg_class c ON c.oid = i.indrelid
    JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
   WHERE c.relnamespace = 'public'::regnamespace
     AND c.relkind = 'r'
     AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint k
                      WHERE k.conindid = i.indexrelid AND k.contype IN ('p', 'u', 'x'))
     AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                      WHERE e.classid = 'pg_catalog.pg_class'::regclass AND e.objid = c.oid AND e.deptype = 'e');
  v := v || E'\n-- ── 6. Índices ──\n' || coalesce(s, '-- (ninguno)') || E'\n';

  -- ── Triggers ──
  SELECT string_agg(
           pg_catalog.pg_get_triggerdef(t.oid) || ';' ||
           CASE t.tgenabled
             WHEN 'D' THEN format(E'\nALTER TABLE %I.%I DISABLE TRIGGER %I;', 'public', c.relname, t.tgname)
             WHEN 'R' THEN format(E'\nALTER TABLE %I.%I ENABLE REPLICA TRIGGER %I;', 'public', c.relname, t.tgname)
             WHEN 'A' THEN format(E'\nALTER TABLE %I.%I ENABLE ALWAYS TRIGGER %I;', 'public', c.relname, t.tgname)
             ELSE ''
           END,
           E'\n' ORDER BY c.relname, t.tgname)
    INTO s
    FROM pg_catalog.pg_trigger t
    JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
   WHERE c.relnamespace = 'public'::regnamespace
     AND NOT t.tgisinternal;
  v := v || E'\n-- ── 7. Triggers ──\n' || coalesce(s, '-- (ninguno)') || E'\n';

  -- ── RLS activado por tabla ──
  SELECT string_agg(
           format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY;', 'public', c.relname) ||
           CASE WHEN c.relforcerowsecurity THEN format(E'\nALTER TABLE %I.%I FORCE ROW LEVEL SECURITY;', 'public', c.relname) ELSE '' END,
           E'\n' ORDER BY c.relname)
    INTO s
    FROM pg_catalog.pg_class c
   WHERE c.relnamespace = 'public'::regnamespace
     AND c.relkind = 'r'
     AND c.relrowsecurity;
  v := v || E'\n-- ── 8. Row Level Security ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  -- ── Políticas (public y storage) ──
  SELECT string_agg(
           format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
                  p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
                  array_to_string(ARRAY(SELECT pg_catalog.quote_ident(r) FROM unnest(p.roles) r), ', '),
                  CASE WHEN p.qual IS NOT NULL THEN E'\n  USING (' || p.qual || ')' ELSE '' END,
                  CASE WHEN p.with_check IS NOT NULL THEN E'\n  WITH CHECK (' || p.with_check || ')' ELSE '' END),
           E'\n' ORDER BY p.schemaname, p.tablename, p.policyname)
    INTO s
    FROM pg_catalog.pg_policies p
   WHERE p.schemaname IN ('public', 'storage');
  v := v || E'\n-- ── 9. Políticas RLS (public y storage.objects) ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  -- ── Comentarios de tablas y columnas ──
  SELECT string_agg(x.stmt, E'\n' ORDER BY x.ord)
    INTO s
    FROM (
      SELECT format('COMMENT ON TABLE %I.%I IS %L;', 'public', c.relname, d.description) AS stmt,
             c.relname || ' 0000' AS ord
        FROM pg_catalog.pg_description d
        JOIN pg_catalog.pg_class c ON c.oid = d.objoid
       WHERE d.classoid = 'pg_catalog.pg_class'::regclass AND d.objsubid = 0
         AND c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
      UNION ALL
      SELECT format('COMMENT ON COLUMN %I.%I.%I IS %L;', 'public', c.relname, a.attname, d.description),
             c.relname || ' ' || lpad(a.attnum::text, 4, '0')
        FROM pg_catalog.pg_description d
        JOIN pg_catalog.pg_class c ON c.oid = d.objoid
        JOIN pg_catalog.pg_attribute a ON a.attrelid = c.oid AND a.attnum = d.objsubid
       WHERE d.classoid = 'pg_catalog.pg_class'::regclass AND d.objsubid > 0
         AND c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
    ) x;
  v := v || E'\n-- ── 10. Comentarios ──\n' || coalesce(s, '-- (ninguno)') || E'\n';

  -- ── Permisos (GRANT) de tablas para anon / authenticated / service_role ──
  SELECT string_agg(x.stmt, E'\n' ORDER BY x.ord)
    INTO s
    FROM (
      SELECT format('REVOKE ALL ON TABLE %I.%I FROM anon, authenticated, service_role;', 'public', c.relname) AS stmt,
             c.relname || ' 0' AS ord
        FROM pg_catalog.pg_class c
       WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
         AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                          WHERE e.classid = 'pg_catalog.pg_class'::regclass AND e.objid = c.oid AND e.deptype = 'e')
      UNION ALL
      SELECT format('GRANT %s ON TABLE %I.%I TO %I;', g.privs, 'public', g.relname, pg_catalog.pg_get_userbyid(g.gid)),
             g.relname || ' 1 ' || pg_catalog.pg_get_userbyid(g.gid)
        FROM (
          SELECT c.relname, a.grantee AS gid,
                 string_agg(a.privilege_type, ', ' ORDER BY a.privilege_type) AS privs
            FROM pg_catalog.pg_class c
            CROSS JOIN LATERAL pg_catalog.aclexplode(c.relacl) a
           WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
             AND pg_catalog.pg_get_userbyid(a.grantee) IN ('anon', 'authenticated', 'service_role')
           GROUP BY c.relname, a.grantee
        ) g
    ) x;
  v := v || E'\n-- ── 11. Permisos de tablas ──\n' || coalesce(s, '-- (ninguno)') || E'\n';

  -- ── Permisos (EXECUTE) de funciones ──
  SELECT string_agg(x.stmt, E'\n' ORDER BY x.ord)
    INTO s
    FROM (
      SELECT format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated, service_role;', p.oid::regprocedure) AS stmt,
             p.proname || ' ' || p.oid::text || ' 0' AS ord
        FROM pg_catalog.pg_proc p
       WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f', 'p') AND p.proacl IS NOT NULL
         AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                          WHERE e.classid = 'pg_catalog.pg_proc'::regclass AND e.objid = p.oid AND e.deptype = 'e')
      UNION ALL
      SELECT format('GRANT EXECUTE ON FUNCTION %s TO %s;', p.oid::regprocedure,
                    CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE pg_catalog.quote_ident(pg_catalog.pg_get_userbyid(a.grantee)) END),
             p.proname || ' ' || p.oid::text || ' 1 ' || a.grantee::text
        FROM pg_catalog.pg_proc p
        CROSS JOIN LATERAL pg_catalog.aclexplode(p.proacl) a
       WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f', 'p')
         AND (a.grantee = 0 OR pg_catalog.pg_get_userbyid(a.grantee) IN ('anon', 'authenticated', 'service_role'))
         AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_depend e
                          WHERE e.classid = 'pg_catalog.pg_proc'::regclass AND e.objid = p.oid AND e.deptype = 'e')
    ) x;
  v := v || E'\n-- ── 12. Permisos de funciones ──\n' || coalesce(s, '-- (ninguno)') || E'\n';

  -- ── Publicación realtime ──
  SELECT string_agg(format('ALTER PUBLICATION %I ADD TABLE %I.%I;', pt.pubname, pt.schemaname, pt.tablename),
                    E'\n' ORDER BY pt.pubname, pt.tablename)
    INTO s
    FROM pg_catalog.pg_publication_tables pt
   WHERE pt.schemaname = 'public';
  v := v || E'\n-- ── 13. Realtime (tablas publicadas) ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  -- ── Buckets de Storage ──
  SELECT string_agg(
           format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %L, %L, %L) ON CONFLICT (id) DO NOTHING;',
                  b.id, b.name, b.public, b.file_size_limit, b.allowed_mime_types),
           E'\n' ORDER BY b.id)
    INTO s
    FROM storage.buckets b;
  v := v || E'\n-- ── 14. Buckets de Storage (solo la definición; los archivos NO van aquí) ──\n'
         || coalesce(s, '-- (ninguno)') || E'\n';

  -- ── Tareas programadas (pg_cron) ──
  s := NULL;
  IF pg_catalog.to_regclass('cron.job') IS NOT NULL THEN
    EXECUTE $q$
      SELECT string_agg(
               format('SELECT cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command)
                 || CASE WHEN j.active THEN '' ELSE ' -- INACTIVA en producción' END,
               E'\n' ORDER BY j.jobname)
        FROM cron.job j
    $q$ INTO s;
  END IF;
  v := v || E'\n-- ── 15. Tareas programadas (pg_cron) ──\n' || coalesce(s, '-- (ninguna)') || E'\n';

  RETURN v;
END;
$fn$;

REVOKE ALL ON FUNCTION public._estructura_bd_ddl() FROM PUBLIC, anon, authenticated;


CREATE OR REPLACE FUNCTION public.exportar_estructura_bd()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $fn$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.usuarios u
     WHERE u.id = (SELECT auth.uid())
       AND u.rol = 'admin'
       AND u.activo = true
  ) THEN
    RAISE EXCEPTION 'Solo un administrador puede exportar la estructura de la base'
      USING ERRCODE = '42501';
  END IF;

  RETURN public._estructura_bd_ddl();
END;
$fn$;

REVOKE ALL ON FUNCTION public.exportar_estructura_bd() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.exportar_estructura_bd() TO authenticated;

NOTIFY pgrst, 'reload schema';
